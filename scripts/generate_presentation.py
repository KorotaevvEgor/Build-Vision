def build_presentation() -> None:
    presentation = Presentation()
    presentation.slide_width = Inches(13.333)
    presentation.slide_height = Inches(7.5)

    title_layout = presentation.slide_layouts[0]
    content_layout = presentation.slide_layouts[1]

    for index, (title_text, bullets) in enumerate(SLIDES):
        layout = title_layout if index == 0 else content_layout
        slide = presentation.slides.add_slide(layout)

        slide.shapes.title.text = title_text
        title_frame = slide.shapes.title.text_frame
        title_frame.paragraphs[0].font.size = Pt(40 if index == 0 else 32)
        title_frame.paragraphs[0].font.bold = True
        title_frame.paragraphs[0].font.color.rgb = ACCENT

        if index == 0:
            subtitle_placeholder = slide.placeholders[1]
            subtitle_placeholder.text = "\n".join(bullets)
            for paragraph in subtitle_placeholder.text_frame.paragraphs:
                paragraph.font.size = Pt(20)
                paragraph.font.color.rgb = MUTED
            continue

        body = slide.placeholders[1]
        text_frame = body.text_frame
        text_frame.clear()
        for line_index, line in enumerate(bullets):
            paragraph = text_frame.paragraphs[0] if line_index == 0 else text_frame.add_paragraph()
            paragraph.text = line
            paragraph.font.size = Pt(20 if line else 8)
            paragraph.font.color.rgb = TEXT if line else MUTED

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    presentation.save(OUTPUT_PATH)
    print(f"Слайдов: {len(SLIDES)}")
    print(f"Сохранено: {OUTPUT_PATH}")


if __name__ == "__main__":
    build_presentation()
